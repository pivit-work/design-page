/** `{{name}}` 자리를 값으로 바꾼다. */
export function fill(template, vars = {}) {
  // 채운 뒤 「{{email}}(으)로」 같은 괄호 꼴 조사를 받침에 맞춘다 (PW-1790 · PW-2259).
  return resolveKoreanParticles(
    String(template).replace(/\{\{(\w+)\}\}/g, (_, k) => (vars[k] == null ? '' : String(vars[k]))),
  );
}
