/**
 * 목록 한 줄 앞에 사람이 직접 친 번호·글머리(「①」「1.」「2)」「-」「•」)를 뗀다 (PW-2190).
 *
 * BIG BETS 처럼 줄마다 목록으로 그리는 글은 회사가 줄 앞에 표시를 이미 쳐 둔 경우가 많다.
 * `<ol>` 번호 위에 그 표시가 남으면 「1. ① …」처럼 번호가 두 번 찍힌다.
 * 표시만 그리는 데서 떼고, 저장된 글은 건드리지 않는다.
 *
 * 숫자는 뒤에 「.」「)」와 빈칸이 올 때만 뗀다 — 「2026년」「3.5% 성장」은 그대로 둔다.
 */
const MARKER = /^\s*(?:[①-⑳]\s*|(?:\d{1,2}[.)]|[-•*·])\s+)/;

export default function stripListMarker(line) {
  return String(line ?? '').replace(MARKER, '');
}
